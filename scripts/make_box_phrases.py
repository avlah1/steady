"""Generate the Box's spoken phrases and build them into the firmware.

Reads the *_PROMPT texts from app/incidents.py, speaks each with Piper (offline text-to-speech),
converts to the Box's format (16 kHz mono 16-bit), evens out the loudness, and writes
firmware/box-audio-test/src/phrases.h. Rerun it whenever a prompt changes, then reflash.

One-time setup (the voice model is ~60 MB, kept out of git):
    mkdir -p models/piper && cd models/piper
    curl -LO https://huggingface.co/rhasspy/piper-voices/resolve/main/en/en_US/lessac/medium/en_US-lessac-medium.onnx
    curl -LO https://huggingface.co/rhasspy/piper-voices/resolve/main/en/en_US/lessac/medium/en_US-lessac-medium.onnx.json

Usage: uv run python -m scripts.make_box_phrases [--model models/piper/en_US-lessac-medium.onnx]
"""

import argparse
import subprocess
import tempfile
import wave
from pathlib import Path

import numpy as np

from app import incidents

RATE = 16000
# Loudest moment of each clip, out of 32767. Matches the playback test that was clear but not
# too loud at Box volume 65. Change the volume on the Box, not this, so every clip stays even.
PEAK = 4000
# Slightly slower than normal speech: easier to follow for an older listener.
LENGTH_SCALE = 1.15

OUT = Path("firmware/box-audio-test/src/phrases.h")


def prompts() -> list[str]:
    return [value for name, value in vars(incidents).items() if name.endswith("_PROMPT")]


def speak(text: str, model: Path) -> tuple[np.ndarray, int]:
    # A real file, not stdout: with more than one sentence Piper goes back to fix the WAV header.
    with tempfile.NamedTemporaryFile(suffix=".wav") as f:
        subprocess.run(
            ["uv", "tool", "run", "--from", "piper-tts", "piper", "-m", str(model),
             "--length-scale", str(LENGTH_SCALE), "-f", f.name],
            input=text.encode(), capture_output=True, check=True,
        )
        with wave.open(f.name) as w:
            return np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float64), w.getframerate()


def resample(samples: np.ndarray, rate: int) -> np.ndarray:
    """Change the sample rate by keeping only the frequencies the new rate can hold (no aliasing)."""
    n = round(len(samples) * RATE / rate)
    spectrum = np.fft.rfft(samples)[: n // 2 + 1]
    return np.fft.irfft(spectrum, n) * n / len(samples)


def trim(samples: np.ndarray, threshold: float = 200) -> np.ndarray:
    """Cut silence at both ends, keeping 50 ms so words don't start abruptly."""
    loud = np.flatnonzero(np.abs(samples) > threshold)
    if len(loud) == 0:
        return samples
    pad = RATE // 20
    return samples[max(loud[0] - pad, 0): loud[-1] + pad]


def to_c_array(name: str, samples: np.ndarray) -> str:
    values = ",".join(str(v) for v in samples)
    return f"static const int16_t {name}[{len(samples)}] = {{{values}}};\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", type=Path, default=Path("models/piper/en_US-lessac-medium.onnx"))
    args = parser.parse_args()

    arrays, table = [], []
    for i, text in enumerate(prompts()):
        samples, rate = speak(text, args.model)
        samples = trim(resample(samples, rate))
        samples = np.round(samples * PEAK / np.abs(samples).max()).astype(np.int16)
        arrays.append(to_c_array(f"phrase_{i}", samples))
        table.append(f'    {{"{text}", phrase_{i}, {len(samples)}}},\n')
        print(f"{len(samples) / RATE:4.1f} s  {text}")

    OUT.write_text(
        "// Generated by scripts/make_box_phrases.py from the *_PROMPT texts in app/incidents.py.\n"
        "// Don't edit: rerun the script. 16 kHz mono 16-bit, peak " f"{PEAK}.\n"
        "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"
        + "".join(arrays)
        + "\nstruct Phrase {\n  const char* text;  // exactly what the backend sends\n"
        "  const int16_t* samples;\n  size_t count;\n};\n\n"
        f"static const Phrase PHRASES[] = {{\n{''.join(table)}}};\n"
        "static const size_t PHRASE_COUNT = sizeof(PHRASES) / sizeof(PHRASES[0]);\n"
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
